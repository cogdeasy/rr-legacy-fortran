#!/bin/sh
#=====================================================================
# RUNEHM   NIGHTLY JOB STREAM FOR THE ENGINE HEALTH MONITORING SYSTEM
#          ROLLS-ROYCE PLC - CIVIL AERO SUPPORT - DERBY
#
# THIS IS THE OPEN SYSTEMS EQUIVALENT OF THE PRODUCTION JOB DECK IN
# JCL/RUNEHM.JCL.  THE STEP NUMBERS, DATA SET NAMES AND CONDITION
# CODES ARE THE SAME ON BOTH, SO THE OPERATIONS MANUAL APPLIES
# WITHOUT AMENDMENT.
#
#   STEP 010  EHMGEN   BUILD THE ENGINE MASTER AND THE DOWNLINK LOG
#   STEP 020  EHMLOD   VALIDATE THE DOWNLINK LOG
#   STEP 030  EHMTRN   FORM THE DETERIORATION TRENDS
#   STEP 040  EHMALR   RAISE THE EXCEEDANCE ALERTS
#   STEP 050  EHMRUL   PROJECT REMAINING LIFE
#   STEP 060  MROPLN   ALLOCATE SHOP VISIT SLOTS
#   STEP 070  FLTRPT   PRINT THE FLEET STATUS REPORT
#
# EVERY STEP READS ITS CONTROL CARD FROM SYSIN AND WRITES ITS PRINT
# FILE TO WORK/SYSPRINT.  A NON ZERO CONDITION CODE FLUSHES THE
# REMAINING STEPS, AS IT DOES ON THE MAINFRAME.
#=====================================================================

BASE=`cd \`dirname $0\`/.. && pwd`
BIN=$BASE/bin
DAT=$BASE/dat
WRK=$BASE/work

mkdir -p $WRK || exit 12
cd $WRK || exit 12

# ---- ALLOCATE THE CONTROL FILES INTO THE WORK LIBRARY ---------------
cp $DAT/PARLIM.DAT . || exit 12
cp $DAT/SHPSLT.DAT . || exit 12
cp $DAT/EHMCTL.DAT . || exit 12

: > SYSPRINT.TXT
: > SYSERR.LOG

# ---- EXECUTE ONE STEP.  A NON ZERO CONDITION CODE FLUSHES THE ------
# ---- REMAINING STEPS, AS IT DOES ON THE MAINFRAME. -----------------
runstep()
{
    STEP=$1
    PGM=$2
    echo "EHM0001I STEP $STEP PGM=$PGM STARTED"
    rm -f SYSERR.DAT
    $BIN/$PGM < EHMCTL.DAT >> SYSPRINT.TXT
    RC=$?
    if [ -s SYSERR.DAT ] ; then
        cat SYSERR.DAT >> SYSERR.LOG
    fi
    echo "EHM0002I STEP $STEP PGM=$PGM ENDED    COND CODE $RC"
    if [ $RC -ne 0 ] ; then
        echo "EHM0004E STEP $STEP ABENDED - REMAINING STEPS FLUSHED"
        echo "EHM0003I JOB ENDED - PRINT FILE IS $WRK/SYSPRINT.TXT"
        exit $RC
    fi
}

runstep 010 EHMGEN
runstep 020 EHMLOD
runstep 030 EHMTRN
runstep 040 EHMALR
runstep 050 EHMRUL
runstep 060 MROPLN
runstep 070 FLTRPT

echo "EHM0003I JOB ENDED - PRINT FILE IS $WRK/SYSPRINT.TXT"
